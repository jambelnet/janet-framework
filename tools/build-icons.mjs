import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { icons } = require('../www/vendor/lucide/lucide.min.js');
const root = new URL('../www/icons/', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('catalog.json', root), 'utf8'));
const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' })[char]);
const categories = new Map(catalog.categories.map(category => [category.id, category]));
const ids = new Set();
const rendered = catalog.icons.map(icon => {
    if (!/^[a-z][a-z0-9-]*$/.test(icon.id) || ids.has(icon.id)) throw new Error('Invalid or duplicate icon ID: ' + icon.id);
    ids.add(icon.id);
    const category = categories.get(icon.category), nodes = icons[icon.glyph];
    if (!category || !/^#[0-9a-f]{6}$/i.test(category.color) || !nodes) throw new Error('Invalid category or Lucide glyph: ' + icon.id);
    const artwork = nodes.map(([tag, attrs]) => '<' + tag + ' ' + Object.entries(attrs).map(([key, value]) => key + '="' + escape(value) + '"').join(' ') + '/>').join('');
    const svg = '<!-- Lucide artwork (c) 2026 Lucide Icons and Contributors; ISC license, see ../LICENSE-lucide.txt. Generated by tools/build-icons.mjs. -->\n' +
        '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64" role="img" aria-labelledby="title">' +
        '<title id="title">' + escape(icon.label) + '</title><rect width="64" height="64" rx="8" fill="' + category.color + '"/>' +
        '<svg x="14" y="14" width="36" height="36" viewBox="0 0 24 24" fill="none" stroke="#fff" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">' + artwork + '</svg></svg>\n';
    return [new URL('default/' + icon.id + '.svg', root), svg];
});
if (process.argv.includes('--check')) {
    for (const [file, svg] of rendered) {
        const actual = await readFile(file, 'utf8');
        if (actual.replaceAll('\r\n', '\n') !== svg) throw new Error('Icon needs regeneration: ' + file.pathname);
    }
    console.log(rendered.length + ' default icons match the catalog and bundled Lucide artwork.');
} else {
    await mkdir(new URL('default/', root), { recursive: true });
    for (const [file, svg] of rendered) await writeFile(file, svg);
    console.log('Generated ' + rendered.length + ' default SVG icons.');
}
